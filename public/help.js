export function renderHelp(view, { h, me }) {
  const isManager = ['manager', 'admin'].includes(me.role);
  const toc = [['h-user', 'מדריך למשתמשים'], ...(isManager ? [['h-manager', 'מדריך למנהלים']] : []), ...(me.role === 'admin' ? [['h-admin', 'לאדמין']] : [])];
  view.replaceChildren(...[
    h('h1', {}, 'עזרה'),
    h('p', { class: 'muted' }, `המדריך מותאם להרשאות שלך (${me.roleLabel || ''}).`),
    toc.length > 1 ? h('nav', { 'aria-label': 'תוכן העזרה' }, h('ul', { class: 'help-toc' }, toc.map(([id, t]) => h('li', {}, h('a', { href: `#${id}`, onclick: (e) => { e.preventDefault(); const el = document.getElementById(id); el?.setAttribute('tabindex', '-1'); el?.focus(); el?.scrollIntoView(); } }, t))))) : null,
    ...userGuide(h, me),
    ...(isManager ? managerGuide(h) : []),
    ...(me.role === 'admin' ? adminGuide(h) : []),
    h('section', { class: 'card help', 'aria-labelledby': 'h-contact' },
      h('h2', { id: 'h-contact' }, 'שאלות ותקלות'),
      h('p', {}, 'בשאלות על בקשה מסוימת פונים למנהל/ת הקבוצה. בבעיות גישה או תקלות פונים לצוות התנועה לחופש המידע: ',
        h('a', { href: 'mailto:office@meida.org.il', dir: 'ltr' }, 'office@meida.org.il'), '.'),
      h('p', {}, h('a', { href: '/accessibility' }, 'הצהרת הנגישות'), ' · ', h('a', { href: '/privacy' }, 'מדיניות הפרטיות'))),
  ].filter(Boolean)); // replaceChildren would print a null
}
